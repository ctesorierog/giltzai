def resolve(cands, tc):
    codes = {c for c, _ in cands}
    if len(codes) == 1:
        return next(iter(codes))
    f = {c for c, t in cands if t == tc}
    return next(iter(f)) if len(f) == 1 else None


def match_street(s):
    k, tc = core(s), tclass(s)
    if not k:
        return None, 0
    if k in idx:
        c = resolve(idx[k], tc)
        if c is not None:
            return c, 100
    for hit in process.extract(k, keys, scorer=fuzz.token_set_ratio, score_cutoff=85, limit=3):
        c = resolve(idx[hit[0]], tc)
        if c is not None:
            return c, hit[1]
    return None, 0


