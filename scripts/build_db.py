CODE = re.compile(r'\b([EHLKAPCTBX])\s*[-·.]?\s*(SS|BI|VI)\s*[-·.]?\s*(\d{3,6})\b')


def norm_code(s):
    """Normalise a Basque tourist-register code to LLL99999 (e.g. 'ess-2758' -> 'ESS00123')."""
    if not isinstance(s, str):
        return None
    u = s.upper()
    m = CODE.search(u) or CODE.search(u.replace(' ', ''))
    if not m:
        return None
    dg = m.group(3)
    if len(dg) == 6:
        dg = dg[:5]  # 6th digit = check digit (seen in the national-number suffix)
    return f'{m.group(1)}{m.group(2)}{int(dg):05d}'


def code_from_national(s):
    """Spain national number ends with the regional code + check digit: ...ESS001233 -> ESS00123."""
    if not isinstance(s, str):
        return None
    m = re.search(r'([EHLKA])(SS|BI|VI)(\d{5,6})$', s.strip().upper())
    return f'{m.group(1)}{m.group(2)}{int(m.group(3)[:5]):05d}' if m else None


STD = re.compile(r'^[A-Z]{3}\d{5}$')


def strip_acc(s):
    return ''.join(c for c in unicodedata.normalize('NFKD', s) if not unicodedata.combining(c))


