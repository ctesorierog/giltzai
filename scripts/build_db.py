    if isinstance(r.code_best, str) and r.code_best[0] in 'HKAPCTBX':
        return 'B_other_licence_type'
    if any(k in nr for k in ['Exempt - hotel', 'Exempt - hostel', 'agrotourism', 'rural tourism', 'tourist apartment']):
        return 'B_other_licence_type'
    if 'seasonal' in rg or nr.startswith('ESFCNT'):
        return 'C_claims_seasonal_rental'
    if isinstance(r.code_best, str):
        return 'D_code_not_in_register'
    return 'E_no_code'


