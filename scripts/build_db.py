def _tok(s):
    return [w for w in re.sub(r'[^A-Z0-9 ]', ' ', strip_acc(s).upper()).split() if w not in STOP]


def core(s):
    """Street name without its type word(s): 'Pl. Easo' -> 'EASO', 'Camino Kalea' -> 'CAMINO', 'GALTZADA NAGUSIA' -> 'NAGUSIA'."""
    if not isinstance(s, str):
        return ''
    t = _tok(s)
    k = t[:]
    while k and k[0] in TYPES:
        k = k[1:]
    while k and k[-1] in TYPES:
        k = k[:-1]
    if not k:  # the name itself is a type-like word (Camino, Aldapa, Ronda): drop only the generic ones
        k = [w for w in t if w not in ('CALLE', 'KALEA', 'K', 'PLAZA', 'PL', 'ENPARANTZA', 'PASEO', 'PASEALEKUA', 'AVENIDA', 'HIRIBIDEA')] or t
    return ' '.join(k)


def tclass(s, default='K'):
    """Street type class used to break ties (Easo Kalea vs Easo Plaza)."""
    if not isinstance(s, str):
        return default
    t = _tok(s)
    ends = [w for w in (t[:1] + t[-1:]) if w in GENERIC]
    return GENERIC[ends[0]] if ends else default


def floor_key(rest):
    """'4º DR' / '04-DR' -> '4-DR'; 'E A' / 'EN-A' / 'BJ' -> '0-A'."""
    if not isinstance(rest, str) or not rest.strip():
        return None
    s = strip_acc(rest.upper()).replace('º', ' ').replace('ª', ' ')
    s = re.sub(r'[^A-Z0-9]+', ' ', s).strip().split()
    if not s:
        return None
    f, door = s[0], ''.join(s[1:])
    if f.isdigit():
        f = str(int(f))
    elif f in ('E', 'EN', 'BJ', 'BAJO', 'BE', 'BEHEA', 'PB'):
        f = '0'
    return f'{f}-{door}'


def clean_obj(df):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype == object:
            df[c] = df[c].map(lambda x: None if x is None or (isinstance(x, float) and np.isnan(x)) else str(x))
    return df


