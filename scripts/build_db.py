    b = (bis or '').upper()
    b = '' if b == 'BIS' else b
    e = g[(g.num == num) & (g.bis == b)]
    q = 'exact'
    if not len(e):
        e = g[g.num == num]
        q = 'number_no_bis'
    if not len(e):
        gg = g[(g.num % 2) == (num % 2)]
        gg = gg if len(gg) else g
        e = gg.iloc[[int((gg.num - num).abs().values.argmin())]]
        q = 'nearest_number'
    r = e.iloc[0]
    return dict(street_code=sc, geocode_quality=q, lat=r.lat, lon=r.lon, street_score=score)


